// Bundles public/ into src/assets.gen.ts so the Worker serves the frontend
// itself: one script to deploy, no separate asset upload.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const FILES = {
  "/index.html": "text/html; charset=utf-8",
  "/app.js": "text/javascript; charset=utf-8",
  "/theme.js": "text/javascript; charset=utf-8",
  "/styles.css": "text/css; charset=utf-8",
};

const assets = {};
for (const [path, type] of Object.entries(FILES)) {
  const body = readFileSync(new URL(`../public${path}`, import.meta.url), "utf8");
  const etag = `"${createHash("sha256").update(body).digest("hex").slice(0, 16)}"`;
  assets[path] = { body, type, etag };
}

writeFileSync(
  new URL("../src/assets.gen.ts", import.meta.url),
  "// Generated by scripts/build-assets.mjs. Do not edit.\n" +
    "export const ASSETS: Record<string, { body: string; type: string; etag: string }> = " +
    JSON.stringify(assets, null, 1) +
    ";\n",
);
console.log(`assets: ${Object.keys(assets).length} files, ${Object.values(assets).reduce((n, a) => n + a.body.length, 0)} bytes`);
